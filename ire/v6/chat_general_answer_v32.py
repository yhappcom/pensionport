"""V32 opt-in ChatGPT-authored general-investment educational answer route.

Avoids pretending V27's legacy lexical-finance facet router can answer generic
behavior/diversification questions. ChatGPT drafts the answer; the deterministic
engine checks source evidence, claim-review closure, response custody and a
small set of fail-closed actionable red flags. It cannot certify meaning truth.
"""
from __future__ import annotations

import re
from pathlib import Path

from .advisory_decision_utility import _ACTION
from .atomic_exchange import audit_host_atomic_exchange
from .chat_led_evidence_v31 import audit_chat_evidence_v31, evaluate_chat_question_v31
from .codec import json_digest, sha256
from .errors import InvalidInput
from .semantic_finance_decision_v25 import _facet
from .source_census_tax_guard_v26 import _EXECUTE, audit_candidate_census

_SUPPORTED = frozenset({'GENERAL_INVESTMENT_BEHAVIOR','ASSET_DIVERSIFICATION'})
_ACTIONABLE = re.compile(r'무조건\s*(?:매수|매도|팔|사)|(?:지금|당장)\s*(?:매수|매도|팔아|사세요)|수익(?:률)?\s*보장|손실\s*없는\s*투자')
_AMOUNT = re.compile(r'(?<![0-9A-Za-z])\d+(?:[.,]\d+)?(?:\s*(?:만|억|원|%|년|개월))?')


def evaluate_chat_general_question_v32(question, *, source,exchange,current_as_of,
                                       primary_evidence,regulatory_decisions,
                                       meaning_reviews,prior_knowledge_reviews,
                                       selected_claim_ids,candidate_dispositions,
                                       host_answer_text,host_answer_review):
    """Non-V5 general educational fallback; all raw answer text stays private.

    Host's full answer is never generated by regexes. This function attests
    that each claimed source support is exact, reviewed, and selected. Scope
    is explicitly general education and never personalized portfolio advice.
    """
    if (type(question) is not str or not question.strip() or
        _facet(question) or _ACTION.search(question) or _EXECUTE.search(question)):
        raise InvalidInput('V32_ONLY_SUPPORTED_GENERAL_EDUCATION_QUESTION')
    if (type(host_answer_text) is not str or
        not 70<=len(host_answer_text)<=3600 or
        _ACTIONABLE.search(host_answer_text)):
        raise InvalidInput('V32_UNSAFE_OR_INCOMPLETE_HOST_ANSWER')
    if _AMOUNT.search(host_answer_text):
        # A general-behavior fallback never self-invents prices, 5% returns or
        # tax figures. Use the legacy numerical V5 route or chat law review.
        raise InvalidInput('V32_NUMERIC_UNSUPPORTED_IN_GENERIC_EDUCATION')
    if (type(selected_claim_ids) is not list or not selected_claim_ids or
        selected_claim_ids!=sorted(set(selected_claim_ids))):
        raise InvalidInput('V32_SELECTED_ATOMS_INVALID')
    vetted=audit_chat_evidence_v31(
        source,exchange,current_as_of=current_as_of,
        primary_evidence=primary_evidence,
        regulatory_decisions=regulatory_decisions,
        meaning_reviews=meaning_reviews,
        prior_knowledge_reviews=prior_knowledge_reviews)
    check=audit_host_atomic_exchange(source,exchange)
    census=audit_candidate_census(question,exchange,selected_claim_ids,
                                  candidate_dispositions,current_as_of)
    reviewed={row['claim_id']:row for row in vetted['claim_review_rows']}
    atoms={a['claim_id']:a for a in exchange['atoms']}
    if any(cid not in atoms or reviewed[cid]['meaning_status'] not in
           ('CHAT_REVIEWED_GENERAL_EDUCATION','CHAT_REVIEWED_CORRECTION_ONLY')
           for cid in selected_claim_ids):
        raise InvalidInput('V32_CITED_ATOM_NOT_CHAT_REVIEWED')
    keys={'schema','question_sha256','answer_sha256','source_sha256','current_as_of',
          'selected_claim_ids','claim_frame_digests','claim_source_ref_digests',
          'general_education_facet','answer_scope','no_trade_instruction',
          'uncertainty_disclosed','reviewer','reason'}
    row=host_answer_review
    if type(row) is not dict or set(row)!=keys:
        raise InvalidInput('V32_HOST_ANSWER_REVIEW_SCHEMA_INVALID')
    expected={
        'schema':'IRE_V6_V32_CHAT_HOST_EDUCATIONAL_ANSWER_REVIEW',
        'question_sha256':sha256(question.encode('utf-8')),
        'answer_sha256':sha256(host_answer_text.encode('utf-8')),
        'source_sha256':source.source_sha256,
        'current_as_of':current_as_of,
        'selected_claim_ids':selected_claim_ids,
        'claim_frame_digests':[json_digest(atoms[cid]) for cid in selected_claim_ids],
        'claim_source_ref_digests':[
             json_digest(atoms[cid]['source_refs']) for cid in selected_claim_ids],
        'answer_scope':'GENERAL_EDUCATION_ONLY',
        'no_trade_instruction':True,'uncertainty_disclosed':True,
        'reviewer':'CHATGPT_CURRENT_TURN',
    }
    if any(row.get(k)!=v for k,v in expected.items()):
        raise InvalidInput('V32_ANSWER_SHA_SOURCE_OR_SCOPE_MISMATCH')
    facet=row['general_education_facet']
    if (facet not in _SUPPORTED or
        type(row['reason']) is not str or
        not 25<=len(row['reason'].strip())<=750):
        raise InvalidInput('V32_EDUCATIONAL_JUSTIFICATION_REQUIRED')
    # Preserve question/quotation distinction: a selected QUESTION without an
    # educational opinion/fact counterpoint cannot support a factual answer.
    if all(atoms[cid]['kind']=='QUESTION' for cid in selected_claim_ids):
        raise InvalidInput('V32_ONLY_SOURCE_QUESTIONS_NO_EDUCATIONAL_SUPPORT')
    receipt={
        'schema':'IRE_V6_V32_HOST_GENERAL_EDUCATION_HASH_ONLY_RECEIPT',
        'question_sha256':expected['question_sha256'],
        'host_answer_sha256':expected['answer_sha256'],
        'source_sha256':source.source_sha256,
        'source_scope':{'first':source.scope_first_cue,'last':source.scope_last_cue,
                        'original_total_cues':len(source.cues)},
        'original_source_scope_full_video':source.scope_first_cue==1 and source.scope_last_cue==len(source.cues),
        'v31_evidence_review_sha256':vetted['receipt_sha256'],
        'question_candidate_census_sha256':census['candidate_receipt_sha256'],
        'source_atomic_exchange_digest':check['atom_candidate_digest'],
        'host_answer_review_sha256':json_digest(row),
        'selected_claim_ids':selected_claim_ids,
        'general_education_facet':facet,
        'actual_legacy_v5_called':False,
        'chat_final_answer_written_and_reviewed':True,
        'automatic_master_knowledge_merge_approved':False,
        'independent_financial_accuracy_certified':False,
        'personalized_financial_trade_or_tax_approved':False,
        'p0_go':False,
        'status':'V32_CHAT_GENERAL_EDUCATION_ONLY_NO_V5_NO_INDEPENDENT_GOLD',
    }
    receipt['receipt_sha256']=json_digest(receipt)
    return {'schema':'IRE_V6_V32_CHAT_GENERAL_EDUCATION_ANSWER',
            'answer_text':host_answer_text,
            'public_hash_only_receipt':receipt,
            'operational_education_only':True,
            'p0_go':False}


def evaluate_chat_irp_paraphrase_v32(root:Path, question, *, host_paraphrase_review,
                                    source, exchange,current_as_of, primary_evidence,
                                    regulatory_decisions,meaning_reviews,
                                    prior_knowledge_reviews,selected_claim_ids,
                                    relevance_decisions,candidate_dispositions):
    """Constrained lexical normalization, with original question hash custody.

    Does NOT rewrite unrelated finance semantics, adjust amounts, or claim
    that equivalence is independently proven. For a compatible IRP payout
    question, the existing V31->V27->V5 branch still does the real work.
    """
    if type(question) is not str or not ('IRP' in question.upper()):
        raise InvalidInput('V32_IRP_PARAPHRASE_SCOPE_INVALID')
    normalized,count=re.subn(r'퇴직금을?\s*받을\s*때', '퇴직금 수령 시', question)
    if count!=1 or normalized==question or _facet(question):
        raise InvalidInput('V32_NO_SAFE_PARAPHRASE_NORMALIZATION_AVAILABLE')
    must={'original_question_sha256':sha256(question.encode('utf-8')),
          'normalized_question_sha256':sha256(normalized.encode('utf-8')),
          'source_sha256':source.source_sha256,
          'reviewer':'CHATGPT_CURRENT_TURN',
          'reviewed_as_of':current_as_of,
          'same_financial_subject_and_condition':True,
          'normalized_question':normalized}
    row=host_paraphrase_review
    if (type(row) is not dict or set(row)!=set(must)|{'reason'} or
        any(row[k]!=v for k,v in must.items()) or
        type(row['reason']) is not str or len(row['reason'].strip())<25 or
        'IRP_INCOME' not in _facet(normalized)):
        raise InvalidInput('V32_IRP_PARAPHRASE_REVIEW_MISSING_OR_DRIFTED')
    r=evaluate_chat_question_v31(root,normalized,source=source,exchange=exchange,
         current_as_of=current_as_of,primary_evidence=primary_evidence,
         regulatory_decisions=regulatory_decisions,
         meaning_reviews=meaning_reviews,
         prior_knowledge_reviews=prior_knowledge_reviews,
         selected_claim_ids=selected_claim_ids,relevance_decisions=relevance_decisions,
         candidate_dispositions=candidate_dispositions)
    receipt={'schema':'IRE_V6_V32_REVIEWED_PARAPHRASE_V5_PATH_RECEIPT',
        'original_question_sha256':must['original_question_sha256'],
        'normalized_question_sha256':must['normalized_question_sha256'],
        'source_sha256':source.source_sha256,
        'host_paraphrase_review_sha256':json_digest(row),
        'v31_answer_receipt_sha256':r['v31_hash_only_answer_receipt']['receipt_sha256'],
        'real_v5_p3_executed':True,
        'semantic_equivalence_independently_certified':False,
        'original_private_archive_verified_inside_this_method':False,
        'personalized_trade_or_tax_approved':False,
        'p0_go':False}
    receipt['receipt_sha256']=json_digest(receipt)
    return {**r,'schema':'IRE_V6_V32_IRP_PARAPHRASE_REAL_V5_ANSWER',
            'v32_original_question_preserved_for_provenance_sha256':must['original_question_sha256'],
            'v32_hash_only_paraphrase_receipt':receipt,'p0_go':False}
