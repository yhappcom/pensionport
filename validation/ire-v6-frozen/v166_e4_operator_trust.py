"""V166 E4 operator-side trust boundary — external secret + latest owner pin.

The E4 HMAC root alone cannot assert trustworthy knowledge if callers copy the
pin from the SQLite/seal. This module requires separate operator-owned key and
pin paths with restrictive permissions. No keys, pins or user SRTs are
generated by the production code or committed to GitHub.

The verifier is deliberately NOT a portfolio advisor. Physical raw SQLite
writes remain possible; they invalidate trusted reads instead of becoming
approved research. This code is POSIX-only and needs deployment with private
owner-managed paths, never under the repository working tree.
"""
from __future__ import annotations

import os
import stat
import tempfile
from contextlib import contextmanager
from pathlib import Path

from ire.v6.errors import InvalidInput, QualityNotProven
from v166_e4_sealed_knowledge import E4SealedKnowledgeStore, _pin_ok

try:
    import fcntl
except ImportError as exc:  # pragma: no cover — cannot silently downgrade
    raise RuntimeError("V166_E4_POSIX_LOCKING_REQUIRED") from exc

E4_OPERATOR_SCHEMA = "IRE_V166_E4_SEPARATE_OPERATOR_TRUST_STORE_V1"


def _error(code):
    raise QualityNotProven("V166_E4_OPERATOR_" + code)


def _require(ok, code):
    if not ok:
        raise InvalidInput("V166_E4_OPERATOR_" + code)


def _separate_path(candidate, db_path):
    p = Path(candidate).expanduser()
    _require(p.is_absolute(), "ABSOLUTE_OPERATOR_PATH_REQUIRED")
    _require(not p.is_symlink(), "SYMLINK_NOT_ALLOWED")
    resolved = p.resolve(strict=False)
    db = Path(db_path).expanduser().resolve(strict=False)
    _require(resolved != db and
             resolved.parent != db.parent and
             db.parent not in resolved.parents and
             resolved not in db.parents,
             "OPERATOR_MUST_BE_OUTSIDE_DATABASE_DIRECTORY")
    _require(resolved.parent.is_dir() and
             not resolved.parent.is_symlink(), "PRIVATE_OPERATOR_DIR_REQUIRED")
    dstat = resolved.parent.stat()
    _require(dstat.st_uid == os.getuid() and
             (stat.S_IMODE(dstat.st_mode) & 0o077) == 0,
             "PRIVATE_OPERATOR_DIR_OWNER_AND_MODE_0700")
    return resolved


def _read_secure(path, *, allow_missing):
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    except FileNotFoundError:
        if allow_missing:
            return None
        _error("REQUIRED_OWNER_FILE_MISSING")
    except OSError as exc:
        raise QualityNotProven("V166_E4_OPERATOR_UNREADABLE_OR_SYMLINK") from exc
    try:
        st = os.fstat(fd)
        _require(stat.S_ISREG(st.st_mode) and st.st_uid == os.getuid() and
                 stat.S_IMODE(st.st_mode) == 0o600,
                 "OWNER_FILE_NOT_PRIVATE_0600")
        data = os.read(fd, 8193)
        _require(len(data) <= 8192, "OWNER_FILE_TOO_LARGE")
        return data
    finally:
        os.close(fd)


def _write_atomic_0600(path, raw):
    parent=path.parent
    fd,name=tempfile.mkstemp(prefix=".e4-owner-",suffix=".new",dir=str(parent))
    try:
        with os.fdopen(fd,"wb") as out:
            out.write(raw)
            out.flush()
            os.fsync(out.fileno())
        os.chmod(name,0o600)
        os.replace(name,path)
        dirfd=os.open(str(parent),os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(dirfd)
        finally:
            os.close(dirfd)
    finally:
        if os.path.exists(name):
            os.unlink(name)


class E4OperatorTrust:
    """Owner-controlled paths, not a secret stored alongside V126 SQLite."""

    def __init__(self, db_path, *, key_path, latest_pin_path):
        self.db_path=Path(db_path).expanduser().resolve(strict=False)
        self.key_path=_separate_path(key_path,self.db_path)
        self.latest_pin_path=_separate_path(latest_pin_path,self.db_path)
        _require(self.key_path!=self.latest_pin_path,
                 "SECRET_AND_PIN_MUST_BE_SEPARATE_FILES")
        key=_read_secure(self.key_path,allow_missing=False)
        _require(key is not None and len(key)>=32 and len(key)<=1024,
                 "EXTERNAL_SECRET_AT_LEAST_32_BYTES")
        self._key=key
        self._initial_owner_pin=self.read_latest_pin(allow_missing=True)

    def read_latest_pin(self, *, allow_missing=False):
        data=_read_secure(self.latest_pin_path,allow_missing=allow_missing)
        if data is None:
            return None
        try:
            pin=data.decode("ascii").strip()
        except UnicodeDecodeError as exc:
            raise QualityNotProven("V166_E4_OPERATOR_INVALID_PIN_BYTES") from exc
        _require(_pin_ok(pin), "OWNER_PIN_SHA256_REQUIRED")
        return pin

    def _new_store(self, pin):
        return E4SealedKnowledgeStore(
            self.db_path,external_signing_key=self._key,
            prior_owner_pin=pin)

    def open_for_new_parent(self):
        """No implicit trust: preexisting data must have an external pin."""
        fresh=self.read_latest_pin(allow_missing=True)
        return self._new_store(fresh)

    def open_verified_read(self):
        pin=self.read_latest_pin(allow_missing=False)
        store=self._new_store(pin)
        verification=store.verify_e4_certificate(
            externally_pinned_seal_sha256=pin)
        return store,pin,verification

    def certified_research_context(self, question, *,
                                   source, exchange, ledger,
                                   selected_knowledge_ids=None,
                                   discourse=None):
        store,pin,_=self.open_verified_read()
        result=store.certified_e2_source_separated_context(
            question,externally_pinned_seal_sha256=pin,
            source=source,exchange=exchange,ledger=ledger,
            selected_knowledge_ids=selected_knowledge_ids,
            discourse=discourse)
        # Detect even a rollover or unauthorized change of external pin
        # while a verified research context was being constructed.
        if self.read_latest_pin(allow_missing=False)!=pin:
            _error("EXTERNAL_PIN_CHANGED_DURING_RESEARCH_READ")
        return {**result,
                "e4_operator_schema":E4_OPERATOR_SCHEMA,
                "operator_external_latest_pin_verified":True,
                "user_portfolio_advice_authorized":False}

    def commit_signed_parent_pin(self, store, new_owner_pin, *,
                                 expected_previous_pin):
        """After parent DB commit, pin only an externally audited E4 seal.

        The explicit expected_previous_pin is caller-supplied and compare-
        and-swapped under an exclusive PRIVATE operator directory lock.
        If crash occurs after DB commit before pin commit, TRUSTED reads
        fail closed; recovery needs manual owner verification, not autopass.
        """
        _require(isinstance(store,E4SealedKnowledgeStore) and
                 store.path==self.db_path and
                 _pin_ok(new_owner_pin), "PIN_STORE_OR_HASH_INVALID")
        _require(expected_previous_pin is None or
                 _pin_ok(expected_previous_pin),
                 "INVALID_EXPECTED_PREVIOUS_PIN")
        lock_path=self.latest_pin_path.parent/".e4-pin-cas.lock"
        fd=os.open(lock_path,os.O_RDWR | os.O_CREAT | os.O_CLOEXEC | os.O_NOFOLLOW,0o600)
        try:
            os.fchmod(fd,0o600)
            fcntl.flock(fd,fcntl.LOCK_EX)
            current=self.read_latest_pin(allow_missing=True)
            if current!=expected_previous_pin:
                _error("PIN_COMPARE_AND_SWAP_CONFLICT")
            # Verify newly committed state against actual signed root,
            # not merely the user-supplied hex in a log message.
            store.verify_e4_certificate(
                externally_pinned_seal_sha256=new_owner_pin)
            _write_atomic_0600(self.latest_pin_path,
                               (new_owner_pin+"\n").encode("ascii"))
            check=self.read_latest_pin(allow_missing=False)
            if check!=new_owner_pin:
                _error("PIN_DURABILITY_READBACK_MISMATCH")
            return {
                "schema":E4_OPERATOR_SCHEMA,
                "status":"E4_OPERATOR_OWNER_PIN_COMMITTED",
                "owner_pin_sha256":new_owner_pin,
                "operator_key_outside_sqlite":True,
                "latest_pin_outside_sqlite":True,
                "full_current_financial_law_approved":False,
                "personal_investment_advice_authorized":False,
                "p0_go":False,
            }
        finally:
            fcntl.flock(fd,fcntl.LOCK_UN)
            os.close(fd)
